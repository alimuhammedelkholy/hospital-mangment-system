CREATE OR ALTER PROCEDURE Clinical.usp_AdmitPatient
 @PatientId BIGINT,@AdmittingDoctorId BIGINT,@BedId BIGINT,@AdmissionType NVARCHAR(50),
 @AdmissionReason NVARCHAR(1000)=NULL,@ExpectedDischargeDate DATE=NULL,@CreatedBy UNIQUEIDENTIFIER=NULL,@AdmissionId BIGINT OUTPUT
AS
BEGIN
 SET NOCOUNT ON; SET XACT_ABORT ON;
 DECLARE @AdmissionNumber NVARCHAR(50);
 BEGIN TRANSACTION;
 BEGIN TRY
   IF NOT EXISTS(SELECT 1 FROM Facility.Bed WITH(UPDLOCK,HOLDLOCK) WHERE BedId=@BedId AND IsDeleted=0 AND BedStatus=N'Available')
       THROW 51001,'Selected bed is not available.',1;
   IF NOT EXISTS(SELECT 1 FROM Patient.Patient WHERE PatientId=@PatientId AND IsDeleted=0)
       THROW 51002,'Patient does not exist or is deleted.',1;
   IF NOT EXISTS(SELECT 1 FROM HR.Employee WHERE EmployeeId=@AdmittingDoctorId AND IsDeleted=0 AND IsActive=1)
       THROW 51003,'Admitting doctor does not exist or is inactive.',1;

   UPDATE Facility.Bed SET BedStatus=N'Occupied',UpdatedAt=SYSUTCDATETIME(),UpdatedBy=@CreatedBy WHERE BedId=@BedId;
   SET @AdmissionNumber=N'ADM-'+CONVERT(NVARCHAR(8),CONVERT(date,SYSUTCDATETIME()),112)+N'-'+
       RIGHT(N'00000000'+CONVERT(NVARCHAR(20),NEXT VALUE FOR dbo.HMSAdmissionSequence),8);

   INSERT INTO Clinical.Admission(AdmissionNumber,PatientId,AdmittingDoctorId,BedId,AdmissionDate,ExpectedDischargeDate,AdmissionType,AdmissionReason,Status,CreatedBy)
   VALUES(@AdmissionNumber,@PatientId,@AdmittingDoctorId,@BedId,SYSUTCDATETIME(),@ExpectedDischargeDate,@AdmissionType,@AdmissionReason,N'Admitted',@CreatedBy);
   SET @AdmissionId=SCOPE_IDENTITY();
   COMMIT;
 END TRY
 BEGIN CATCH
   IF XACT_STATE()<>0 ROLLBACK; THROW;
 END CATCH
END;
GO

CREATE OR ALTER PROCEDURE Clinical.usp_TransferPatientBed
 @AdmissionId BIGINT,@NewBedId BIGINT,@RequestedBy BIGINT=NULL,@Reason NVARCHAR(1000)=NULL,@BedTransferId BIGINT OUTPUT
AS
BEGIN
 SET NOCOUNT ON; SET XACT_ABORT ON;
 BEGIN TRANSACTION;
 BEGIN TRY
   DECLARE @OldBedId BIGINT;
   SELECT @OldBedId=BedId FROM Clinical.Admission WITH(UPDLOCK,HOLDLOCK) WHERE AdmissionId=@AdmissionId AND Status=N'Admitted' AND IsDeleted=0;
   IF @OldBedId IS NULL THROW 51020,'Active admission not found.',1;
   IF @OldBedId=@NewBedId THROW 51021,'Destination bed must differ.',1;
   IF NOT EXISTS(SELECT 1 FROM Facility.Bed WITH(UPDLOCK,HOLDLOCK) WHERE BedId=@NewBedId AND BedStatus=N'Available' AND IsDeleted=0)
       THROW 51022,'Destination bed is not available.',1;

   UPDATE Facility.Bed SET BedStatus=N'Cleaning',UpdatedAt=SYSUTCDATETIME() WHERE BedId=@OldBedId;
   UPDATE Facility.Bed SET BedStatus=N'Occupied',UpdatedAt=SYSUTCDATETIME() WHERE BedId=@NewBedId;

   INSERT INTO Clinical.BedTransfer(AdmissionId,FromBedId,ToBedId,RequestedAt,ExecutedAt,Status,Reason,RequestedBy,ExecutedBy)
   VALUES(@AdmissionId,@OldBedId,@NewBedId,SYSUTCDATETIME(),SYSUTCDATETIME(),N'Completed',@Reason,@RequestedBy,@RequestedBy);
   SET @BedTransferId=SCOPE_IDENTITY();
   UPDATE Clinical.Admission SET BedId=@NewBedId,UpdatedAt=SYSUTCDATETIME() WHERE AdmissionId=@AdmissionId;
   COMMIT;
 END TRY
 BEGIN CATCH
   IF XACT_STATE()<>0 ROLLBACK; THROW;
 END CATCH
END;
