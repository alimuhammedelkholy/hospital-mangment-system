CREATE OR ALTER PROCEDURE Clinical.usp_DischargePatient
 @AdmissionId BIGINT,@DischargeDate DATETIME2(3)=NULL,@DischargedBy BIGINT,
 @FinalDiagnosis NVARCHAR(MAX)=NULL,@HospitalCourse NVARCHAR(MAX)=NULL,@DischargeMedications NVARCHAR(MAX)=NULL,
 @FollowUpInstructions NVARCHAR(MAX)=NULL,@CreatedBy UNIQUEIDENTIFIER=NULL
AS
BEGIN
 SET NOCOUNT ON; SET XACT_ABORT ON; SET @DischargeDate=ISNULL(@DischargeDate,SYSUTCDATETIME());
 BEGIN TRANSACTION;
 BEGIN TRY
   DECLARE @BedId BIGINT,@AdmissionDate DATETIME2(3);
   SELECT @BedId=BedId,@AdmissionDate=AdmissionDate FROM Clinical.Admission WITH(UPDLOCK,HOLDLOCK)
   WHERE AdmissionId=@AdmissionId AND Status=N'Admitted' AND IsDeleted=0;
   IF @BedId IS NULL THROW 51030,'Active admission not found.',1;
   IF @DischargeDate<@AdmissionDate THROW 51031,'Discharge date precedes admission date.',1;

   UPDATE Clinical.Admission SET DischargeDate=@DischargeDate,Status=N'Discharged',UpdatedAt=SYSUTCDATETIME(),UpdatedBy=@CreatedBy WHERE AdmissionId=@AdmissionId;
   INSERT INTO Clinical.DischargeSummary(AdmissionId,DischargeDate,FinalDiagnosis,HospitalCourse,DischargeMedications,FollowUpInstructions,DischargedBy,CreatedBy)
   VALUES(@AdmissionId,@DischargeDate,@FinalDiagnosis,@HospitalCourse,@DischargeMedications,@FollowUpInstructions,@DischargedBy,@CreatedBy);
   UPDATE Facility.Bed SET BedStatus=N'Cleaning',UpdatedAt=SYSUTCDATETIME(),UpdatedBy=@CreatedBy WHERE BedId=@BedId;
   COMMIT;
 END TRY
 BEGIN CATCH
   IF XACT_STATE()<>0 ROLLBACK; THROW;
 END CATCH
END;
GO

CREATE OR ALTER PROCEDURE Security.usp_RotateRefreshToken
 @UserId UNIQUEIDENTIFIER,@CurrentRefreshTokenHash VARBINARY(64),@NewRefreshTokenHash VARBINARY(64),
 @NewJwtId UNIQUEIDENTIFIER,@NewExpiresAt DATETIME2(3),@DeviceIP VARCHAR(45)=NULL,@UserAgent NVARCHAR(1000)=NULL,
 @CreatedBy UNIQUEIDENTIFIER=NULL,@NewRefreshTokenId UNIQUEIDENTIFIER OUTPUT
AS
BEGIN
 SET NOCOUNT ON; SET XACT_ABORT ON;
 BEGIN TRANSACTION;
 BEGIN TRY
   DECLARE @CurrentTokenId UNIQUEIDENTIFIER;
   SELECT @CurrentTokenId=RefreshTokenId FROM Security.RefreshToken WITH(UPDLOCK,HOLDLOCK)
   WHERE UserId=@UserId AND TokenHash=@CurrentRefreshTokenHash AND RevokedAt IS NULL AND UsedAt IS NULL
     AND ExpiresAt>SYSUTCDATETIME() AND IsDeleted=0;
   IF @CurrentTokenId IS NULL THROW 51010,'Refresh token is invalid, expired, revoked, or already used.',1;

   SET @NewRefreshTokenId=NEWSEQUENTIALID();
   INSERT INTO Security.RefreshToken(RefreshTokenId,UserId,JwtId,TokenHash,ExpiresAt,IssuedAt,DeviceIP,UserAgent,CreatedBy)
   VALUES(@NewRefreshTokenId,@UserId,@NewJwtId,@NewRefreshTokenHash,@NewExpiresAt,SYSUTCDATETIME(),@DeviceIP,@UserAgent,@CreatedBy);
   UPDATE Security.RefreshToken SET UsedAt=SYSUTCDATETIME(),ReplacedByTokenId=@NewRefreshTokenId WHERE RefreshTokenId=@CurrentTokenId;
   COMMIT;
 END TRY
 BEGIN CATCH
   IF XACT_STATE()<>0 ROLLBACK; THROW;
 END CATCH
END;
GO

CREATE OR ALTER PROCEDURE Security.usp_RecordAuthenticationAttempt
 @UserId UNIQUEIDENTIFIER,@IsSuccessful BIT,@FailureReason NVARCHAR(300)=NULL,@IPAddress VARCHAR(45)=NULL,@UserAgent NVARCHAR(1000)=NULL,
 @LockoutThreshold INT=5,@LockoutMinutes INT=15
AS
BEGIN
 SET NOCOUNT ON; SET XACT_ABORT ON;
 BEGIN TRANSACTION;
 BEGIN TRY
   INSERT INTO Security.LoginHistory(UserId,IsSuccessful,FailureReason,IPAddress,UserAgent)
   VALUES(@UserId,@IsSuccessful,@FailureReason,@IPAddress,@UserAgent);
   IF @IsSuccessful=1
     UPDATE Security.AppUser SET FailedLoginCount=0,LockedUntil=NULL,LastLoginAt=SYSUTCDATETIME(),UpdatedAt=SYSUTCDATETIME() WHERE UserId=@UserId;
   ELSE
     UPDATE Security.AppUser SET FailedLoginCount=FailedLoginCount+1,
       LockedUntil=CASE WHEN FailedLoginCount+1>=@LockoutThreshold THEN DATEADD(MINUTE,@LockoutMinutes,SYSUTCDATETIME()) ELSE LockedUntil END,
       UpdatedAt=SYSUTCDATETIME() WHERE UserId=@UserId;
   COMMIT;
 END TRY
 BEGIN CATCH
   IF XACT_STATE()<>0 ROLLBACK; THROW;
 END CATCH
END;
GO

